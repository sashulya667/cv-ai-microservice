def _extract_criteria_labels(user_prompt: str) -> list[str]:
    """Извлекает labels критериев из промпта для формирования динамического мока."""
    matches = re.findall(r'"label":\s*"([^"]+)"', user_prompt)
    return list(dict.fromkeys(matches))


def _build_candidate_rank_payload(user_prompt: str) -> dict:
    labels = _extract_criteria_labels(user_prompt)
    if not labels:
        return _CANDIDATE_RANK_PAYLOAD

    template = _CANDIDATE_RANK_PAYLOAD["criteria_results"][0]
    criteria_results = [
        {"label": label, "score": 80, "explanation": template["explanation"]}
        for label in labels
    ]
    return {**_CANDIDATE_RANK_PAYLOAD, "criteria_results": criteria_results}


