import json
from datetime import date

from app.features.candidate_rank.schemas import SearchCriterion
from app.features.shared.schemas import Resume, Vacancy


def system_prompt(version: str) -> str:
    if version == "v1":
        today = date.today().strftime("%d.%m.%Y")
        return (
            f"Сегодняшняя дата: {today}. "
            "Используй её при расчёте стажа, определении текущего места работы и оценке актуальности опыта. "
            "Ты — система прескоринга кандидатов для работодателей. "
            "Твоя задача — объективно оценить соответствие кандидата вакансии по конкретным критериям. "
            "Ты НЕ карьерный консультант. Ты — аналитический инструмент, который ищет доказательства соответствия. "
            "\n\n"
            "Методология оценки:\n"
            "1. CRITERIA SCORING: Оцени каждый переданный критерий по шкале 0-100 на основе данных резюме.\n"
            "2. RADAR: Выставь оценки по пяти осям: skills, experience, domain, location, languages. "
            "Каждая ось считается по своей рубрике независимо; не выводи оси из общего впечатления.\n"
            "3. RADAR_EXPLANATIONS: Кратко (1–2 предложения) объясни каждую ось радара.\n"
            "4. SUMMARY: Напиши конкретный абзац о кандидате — ключевые компетенции, домен, зарплатные ожидания, доступность.\n"
            "5. INTERVIEW_QUESTIONS: Сформулируй вопросы к интервью, которые помогут проверить пробелы, риски и ключевые требования вакансии.\n"
            "\n"
            "Данные переданы в структурированном JSON. "
            "Не выдумывай факты. Если в резюме нет evidence по критерию — это низкий балл, скажи прямо. "
            "Возвращай ТОЛЬКО валидный JSON строго по схеме, без лишних ключей. "
            "НЕ оборачивай ответ в ```json``` блок — только чистый JSON. "
            "HTML-разметка допустима внутри текстового поля summary. "
            "ВЕСЬ ТЕКСТ В JSON ДОЛЖЕН БЫТЬ СТРОГО НА РУССКОМ ЯЗЫКЕ."
        )
    return system_prompt("v1")


def user_prompt(
    *,
    vacancy: Vacancy,
    required_criteria: list[SearchCriterion],
    desired_criteria: list[SearchCriterion],
    resume: Resume,
) -> str:
    vacancy_json = json.dumps(vacancy.model_dump(exclude_none=True), ensure_ascii=False, indent=2)
    resume_json = json.dumps(resume.model_dump(exclude_none=True), ensure_ascii=False, indent=2)

    all_criteria = [
        {"label": c.label, "value": c.value, "is_required": True}
        for c in required_criteria
    ] + [
        {"label": c.label, "value": c.value, "is_required": False}
        for c in desired_criteria
    ]
    criteria_json = json.dumps(all_criteria, ensure_ascii=False, indent=2)

    return f"""[CANDIDATE_RANK]

ВАКАНСИЯ (JSON):
{vacancy_json}

КРИТЕРИИ ОЦЕНКИ (JSON):
{criteria_json}

РЕЗЮМЕ КАНДИДАТА (JSON):
{resume_json}

Верни JSON ТОЧНО по схеме:
{{
  "criteria_results": [
    {{
      "label": "<точный label из критериев>",
      "score": int,
      "explanation": "<конкретное объяснение на основе данных резюме>"
    }}
  ],
  "radar": {{
    "skills": int,
    "experience": int,
    "domain": int,
    "location": int,
    "languages": int
  }},
  "radar_explanations": {{
    "skills": "<1–2 предложения>",
    "experience": "<1–2 предложения>",
    "domain": "<1–2 предложения>",
    "location": "<1–2 предложения>",
    "languages": "<1–2 предложения>"
  }},
  "strengths": ["<сильная сторона 1>", "<сильная сторона 2>"],
  "risks": ["<риск 1>", "<риск 2>"],
  "summary": "<развёрнутый абзац: компетенции, домен, зарплата, доступность, форматы работы>",
  "interview_questions": ["<вопрос 1>", "<вопрос 2>", "<вопрос 3>"]
}}

БАЗОВЫЕ ПРАВИЛА:
- Вывод ТОЛЬКО валидный JSON (без текста вне JSON, без лишних ключей). НЕ оборачивай в ```json```.
- Все строки в JSON — строго на русском языке.
- Все числовые поля: 0..100.
- Не выдумывай факты. Каждый score основан на конкретных данных резюме.
- criteria_results должен содержать запись для КАЖДОГО критерия из списка, в том же порядке.
- label в criteria_results должен совпадать ТОЧНО с label из критериев.
- strengths: минимум 2 пункта, максимум 4, только факты из резюме.
- risks: минимум 1 пункт, максимум 3, только факты из резюме.
- interview_questions: минимум 3 пункта, максимум 6.
- ФОРМАТИРОВАНИЕ поля summary — используй HTML:
  · <span style='color:#a5ce46'>текст</span> — для ключевых технологий, цифр, критичных выводов
  · \n\n — между смысловыми абзацами
  · НЕ используй Markdown (**, ##), таблицы, другие HTML-теги
  · ВАЖНО: внутри JSON-строки используй ТОЛЬКО одинарные кавычки в HTML-атрибутах

═══════════════════════════════════════════════════════════════════
ИНСТРУКЦИЯ ПО ОЦЕНКЕ CRITERIA_RESULTS
═══════════════════════════════════════════════════════════════════

Для каждого критерия:
- is_required=true: критично, низкий score при отсутствии evidence снижает итог существенно.
- is_required=false: желательно, отсутствие не катастрофично.

score 90-100: полное прямое подтверждение в резюме с конкретными данными.
score 70-89: есть evidence, но не полное совпадение.
score 50-69: частичное или косвенное совпадение.
score 0-49: слабое или отсутствующее совпадение.

═══════════════════════════════════════════════════════════════════
ИНСТРУКЦИЯ ПО RADAR
═══════════════════════════════════════════════════════════════════

Каждая ось — независимая оценка 0..100 по своей рубрике.
Оси сопоставимы между кандидатами одного batch: одна шкала, одни правила.
Не подменяй оси оценками из criteria_results: must/desired критерии живут только в criteria_results.
Не пытайся «подогнать» оси под красивый общий балл.

skills (0-100): совпадение стека/навыков с вакансией.
Сравни resume.skills + описания опыта с vacancy.skills и требованиями в description.
Разный стек у разных кандидатов → заметно разный skills, не «всем ~75».

experience (0-100): уровень / длительность / сеньорность vs требования вакансии.
Учитывай: годы опыта, сложность задач, прогрессия уровня, experienceRequired.

domain (0-100): отрасль, тип задач, контекст опыта vs вакансия.
Сравни домен компаний и задач в опыте с specialization / description вакансии.
Не используй domain как свалку для must/desired критериев.

location (0-100): формат работы (remote / hybrid / office) + город / готовность к релокации.
Оцени совместимость workFormats кандидата с workFormat вакансии.
Если в вакансии указан город — учитывай совпадение / релокацию.
Remote вакансия НЕ означает автоматически location=100: remote — про формат, не про идеальную локацию.
Высокий балл — когда формат совместим и (если релевантно) город/релокация согласованы.

languages (0-100): языки кандидата vs языковые требования вакансии.
Оцени по resume.languages относительно явных требований в вакансии/критериях.
Если вакансия и критерии НЕ требуют иностранных языков — всегда ровно 75 (нейтральный baseline).
Не ставь 0 и не ставь 100 при отсутствии языковых требований.

═══════════════════════════════════════════════════════════════════
ИНСТРУКЦИЯ ПО RADAR_EXPLANATIONS
═══════════════════════════════════════════════════════════════════

Для каждой оси радара — 1–2 коротких предложения на русском.
Объясни, на каких фактах из резюме/вакансии основана оценка.
Не копируй друг друга; каждая ось — своё обоснование.

═══════════════════════════════════════════════════════════════════
ИНСТРУКЦИЯ ПО STRENGTHS И RISKS
═══════════════════════════════════════════════════════════════════

strengths (2-4 пункта):
- Конкретные сильные стороны кандидата относительно данной вакансии.
- Называй конкретные навыки, инструменты, цифры, достижения — только то, что есть в резюме.
- Примеры: "5 лет коммерческого опыта водителем категории C", "Опыт в строительстве (ПИК)", "Зарплатные ожидания в рамках вилки".

risks (1-3 пункта):
- Конкретные риски или пробелы кандидата относительно данной вакансии.
- Если серьёзных рисков нет — укажи один пункт с минимальным риском или "Существенных рисков не выявлено".
- Примеры: "Нет подтверждённого опыта в сфере логистики", "Английский не указан в резюме", "Только 1 год опыта при требовании 3+".

═══════════════════════════════════════════════════════════════════
ИНСТРУКЦИЯ ПО SUMMARY
═══════════════════════════════════════════════════════════════════

summary (1 абзац, 4-6 предложений):
- Ключевые компетенции и навыки кандидата и их соответствие требованиям.
- Домен / отрасль опыта.
- Зарплатные ожидания (если указаны) vs вилка вакансии.
- Формат работы и локация.
- Общий вывод о пригодности для вакансии.

КРИТИЧНО: Будь конкретным. Называй конкретные навыки, инструменты, цифры, названия компаний из резюме.
Ключевые компетенции, термины и цифры оборачивай в <span style='color:#a5ce46'>...</span>.
Пример: "Кандидат имеет <span style='color:#a5ce46'>6 лет опыта</span> в должности <span style='color:#a5ce46'>механика</span>, специализация — <span style='color:#a5ce46'>ремонт дизельных двигателей</span>."

═══════════════════════════════════════════════════════════════════
ИНСТРУКЦИЯ ПО INTERVIEW_QUESTIONS
═══════════════════════════════════════════════════════════════════

interview_questions (3–6 вопросов):
- Конкретные вопросы для интервью именно с этим кандидатом на эту вакансию.
- Приоритизируй проверку risks, слабых criteria_results и ключевых требований вакансии.
- Вопросы должны быть открытыми, практическими, без общих клише вроде "расскажите о себе".
- Опирайся на факты из резюме и требования вакансии; не выдумывай опыт кандидата.
- Каждый элемент — одна готовая формулировка вопроса на русском языке.
""".strip()
