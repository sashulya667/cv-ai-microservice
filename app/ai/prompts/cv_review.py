from datetime import date


def system_prompt(version: str) -> str:
    if version == "v1":
        today = date.today().strftime("%d.%m.%Y")
        return (
            f"Сегодняшняя дата: {today}. "
            "Используй её при расчёте стажа, определении текущего места работы и оценке актуальности опыта. "
            "Ты — опытный рекрутер и ATS-специалист. "
            "Оцениваешь резюме по ясности, структуре, доказательности (метрики/результаты) "
            "и читабельности для ATS. "
            "Данные резюме переданы в структурированном JSON-формате — опирайся строго на них, не выдумывай факты. "
            "Если поле отсутствует или пустое — учитывай это как недостаток (например, нет описания опыта). "
            "Возвращай ТОЛЬКО валидный JSON строго по схеме, без лишних ключей. "
            "НЕ оборачивай ответ в ```json``` блок — только чистый JSON. "
            "Markdown-разметка допустима внутри текстовых полей JSON. "
            "ВЕСЬ ТЕКСТ В JSON ДОЛЖЕН БЫТЬ СТРОГО НА РУССКОМ ЯЗЫКЕ."
        )
    return system_prompt("v1")


def review_user_prompt(*, resume_json: str) -> str:
    return f"""РЕЗЮМЕ КАНДИДАТА (JSON):
{resume_json}

Верни JSON ТОЧНО по схеме:
{{
  "overall_score": int,
  "ats_score": int,
  "summary": str,
  "strengths": [str, ...],
  "weaknesses": [str, ...],
  "improvements": [str, ...],
  "experience_gaps": [str, ...],
  "section_feedback": {{
    "<название_раздела>": "<обратная_связь>"
  }}
}}

Правила:
- Вывод ТОЛЬКО валидный JSON (без пояснений вне JSON, без лишних ключей). НЕ оборачивай в ```json```.
- Все строки в JSON — строго на русском языке.
- overall_score и ats_score: 0..100.
- Опирайся строго на данные резюме. Если поле не заполнено — это недостаток, укажи его явно.
- ЗАПРЕЩЕНО использовать JSON-нотацию и сырые имена полей API в тексте ответа
  (workExperiences[0].description, endDate, isCurrent, endYear, startDate, companyName и т.п.).
  Переводи смысл на русский и ссылайся человекочитаемо:
  "в описании опыта работы в компании X", "дата окончания", "статус текущего места работы",
  "год окончания обучения", "признак текущего обучения", "в разделе Образование для вуза Y".
- ФОРМАТИРОВАНИЕ текстовых полей (summary, значения section_feedback) — используй Markdown:
  · **жирный** — для ключевых терминов, технологий, критичных проблем
  · \n\n — между смысловыми абзацами
  · НЕ используй заголовки (#, ##), таблицы, HTML-теги, горизонтальные линии
  · Элементы массивов (strengths, weaknesses, improvements, experience_gaps) — одна строка без переносов, **жирный** только для ключевого термина в начале

- summary: 5–8 предложений.
  Структура:
  1) Общее впечатление (1-2 предложения)
  2) Главные сильные стороны (2-3 конкретных пункта)
  3) Главные проблемы (2-3 конкретных пункта)
  4) Топ-3 приоритета для улучшения
  5) Прогноз по ATS-проходимости

- strengths: 5–8 пунктов, максимально конкретные.
  Формат: "Что хорошо + почему это важно + где именно в резюме"
  Пример: "Чёткое описание достижений с метриками в опыте работы (например, 'увеличил конверсию на 25%') — повышает доверие рекрутера"
  НЕ пиши общие фразы типа "хороший опыт работы" — ВСЕГДА конкретизируй.

- weaknesses: 5–8 пунктов, максимально конкретные.
  Формат: "Что не так + как это проявляется + почему это проблема"
  Пример: "Описания опыта работы без результатов ('отвечал за разработку') — рекрутер не видит реального вклада"
  Приоритизируй: сначала критичные проблемы (блокеры для ATS/рекрутера), потом менее важные.

- improvements: 8–12 пунктов, максимально практичные, в порядке приоритета.
  Формат: "ЧТО сделать + ГДЕ в резюме + КАК именно (пример)"
  Пример: "В опыте работы, для каждой позиции добавить 2-3 буллета с измеримыми достижениями. Формула: 'Глагол + что сделал + результат в цифрах'. Пример: 'Оптимизировал процесс деплоя, сократив время релиза с 2 часов до 20 минут'"
  Сначала правки с максимальным ROI.

- experience_gaps: список пробелов в карьере.
  Анализируй даты startDate/endDate в workExperiences. Если пробел > 3 месяцев — укажи его.
  Формат каждого пункта: "Пробел между [компания1] и [компания2]: [дата начала] – [дата конца] (~N мес.)"
  Если пробелов нет — верни пустой массив [].

- section_feedback: используй смысловые названия разделов резюме на русском.
  Стандартные разделы: "Опыт работы", "Навыки", "Образование", "Языки", "Сертификаты", "Портфолио", "Рекомендации", "О себе".
  Для каждого присутствующего раздела:
  1) Что есть сейчас (1-2 предложения — объективная оценка)
  2) Что не так (конкретные проблемы)
  3) Что исправить (3-5 конкретных действий с примерами)
  4) Приоритет (что критично, что желательно)

ATS-проверки (учти в оценке и рекомендациях):
- Структура: наличие стандартных секций (Опыт, Навыки, Образование, Языки, Сертификаты)
- Навыки: наличие ключевых технологий + их подтверждение в опыте работы
- Достижения: измеримость (цифры, метрики, конкретные результаты), а не просто обязанности
- Формулировки: глаголы действия (Разработал, Внедрил, Оптимизировал), отсутствие воды и общих фраз
- Красные флаги: пробелы в опыте, несостыковки дат, слишком частая смена работы
- Согласованность статуса «текущее» с датами (критично для ATS/рекрутера):
  · Опыт работы: если указана дата окончания (в т.ч. будущая) при статусе «не текущая работа» /
    или наоборот «текущая работа» при уже прошедшей дате окончания — это логическое противоречие, укажи явно.
  · Образование: если год окончания в прошлом, а статус «учёба продолжается» — противоречие;
    если учёба помечена как текущая, не должно быть завершённого года окончания в прошлом.
  Формулируй без имён полей API: "в опыте работы в компании X дата окончания …, но позиция не отмечена как текущая".

ВАЖНО: Избегай общих фраз. Каждая рекомендация должна быть actionable.
""".strip()


def compare_user_prompt(*, current_resume_json: str, previous_resume_json: str) -> str:
    return f"""ТЕКУЩАЯ ВЕРСИЯ РЕЗЮМЕ (JSON):
{current_resume_json}

ПРЕДЫДУЩАЯ ВЕРСИЯ РЕЗЮМЕ (JSON):
{previous_resume_json}

Верни JSON ТОЧНО по схеме (ДРУГАЯ схема — только дельта!):
{{
  "current_overall_score": int,
  "current_ats_score": int,
  "previous_overall_score": int,
  "previous_ats_score": int,
  "delta_overall": int,
  "delta_ats": int,
  "comparison_summary": str,
  "improvements_made": [str, ...],
  "regressions": [str, ...],
  "still_broken": [str, ...],
  "next_steps": [str, ...]
}}

Твоя задача — СРАВНИТЬ две версии и вернуть только дельту изменений.

Правила:
- Вывод ТОЛЬКО валидный JSON (без пояснений вне JSON, без лишних ключей). НЕ оборачивай в ```json```.
- Все строки в JSON — строго на русском языке.
- Оцени ОБЕ версии независимо, затем вычисли дельту.
- ЗАПРЕЩЕНО использовать JSON-нотацию и сырые имена полей API в тексте ответа
  (workExperiences[0].description, endDate, isCurrent, endYear, startDate, companyName и т.п.).
  Переводи смысл на русский и ссылайся человекочитаемо:
  "в описании опыта работы в компании X", "дата окончания", "статус текущего места работы",
  "год окончания обучения", "признак текущего обучения", "в разделе Образование для вуза Y".
  ПЛОХО: "указана `endDate` …, но `isCurrent` установлено в `false`".
  ХОРОШО: "в опыте работы в компании Kaspi.kz указана дата окончания 01.10.2026, но позиция не отмечена как текущая".
- ФОРМАТИРОВАНИЕ текстового поля (comparison_summary) — используй Markdown:
  · **жирный** — для ключевых терминов и критичных выводов
  · \n\n — между смысловыми абзацами
  · НЕ используй заголовки (#, ##), таблицы, HTML-теги, горизонтальные линии
  · Элементы массивов (improvements_made, regressions, still_broken, next_steps) — одна строка без переносов, **жирный** только для ключевого термина в начале

1. current_overall_score, current_ats_score: оценки текущей версии (0..100)
2. previous_overall_score, previous_ats_score: оценки предыдущей версии (0..100)
3. delta_overall = current_overall_score - previous_overall_score
4. delta_ats = current_ats_score - previous_ats_score

5. comparison_summary: 3-5 предложений — общий вердикт:
   - Стоило ли вносить эти правки?
   - Какой главный эффект от изменений?
   - Прогноз: помогут ли эти правки на собеседованиях?

6. improvements_made: 5-10 пунктов — что КОНКРЕТНО улучшилось.
   Формат: "ЧТО изменилось + БЫЛО vs СТАЛО + почему это лучше"
   НЕ пиши общее "стало лучше" — ВСЕГДА показывай примеры текста до/после.

7. regressions: 3-7 пунктов — что ухудшилось или потеряно.
   Если ничего не ухудшилось — верни пустой массив [].

8. still_broken: 5-8 пунктов — проблемы, которые БЫЛИ в старой версии и НЕ ИСПРАВЛЕНЫ в новой.
   Приоритизируй: сначала блокеры для ATS/рекрутера.
   Обязательно проверяй согласованность статуса «текущее» с датами в текущей версии:
   · Опыт работы: дата окончания (в т.ч. будущая) при статусе «не текущая» / «текущая» при уже завершённой дате — противоречие.
   · Образование: год окончания в прошлом при статусе «учёба продолжается» — противоречие.
   Формулируй по-человечески, без имён полей API.

9. next_steps: 5-7 пунктов — конкретные действия для следующей итерации, в порядке приоритета.
   Формат: "ЧТО сделать + ГДЕ в резюме + КАК именно (пример)"
   Если есть противоречия дат и статуса текущего места работы/учёбы — включи исправление в топ приоритетов.

ВАЖНО:
- Не выдумывай факты — только то, что реально есть в переданных данных.
- Если в новой версии ничего не поменялось — честно скажи (delta = 0, improvements_made = [], regressions = []).
""".strip()
